-- Optimum Service AI — modelo de datos inicial (Supabase / Postgres)
-- Basado en la app Glide actual; ver docs/analisis-app-glide.md

create extension if not exists "pgcrypto";

-- ---------- Catálogos ----------
create type rol_usuario   as enum ('admin', 'tecnico', 'vendedor');
create type tipo_trabajo  as enum ('mantenimiento', 'revision', 'instalacion', 'arranque', 'ensamblaje');
create type lugar_trabajo as enum ('en_cliente', 'en_oficina');
create type estado_trabajo as enum ('abierto', 'en_progreso', 'cerrado', 'cancelado');
create type estado_visita  as enum ('programada', 'en_curso', 'finalizada', 'cancelada');

create table ciudades        (id serial primary key, nombre text not null unique);
create table industrias      (id serial primary key, nombre text not null unique);
create table lineas_producto (id serial primary key, nombre text not null unique);

-- ---------- Personas ----------
create table perfiles (
  id           uuid primary key references auth.users on delete cascade,
  nombre       text not null,
  email        text not null unique,
  telefono     text,
  rol          rol_usuario not null default 'tecnico',
  departamento text,
  ciudad_id    int references ciudades,
  foto_url     text,
  activo       boolean not null default true,
  creado_en    timestamptz not null default now()
);

-- ---------- Clientes y equipos ----------
create table clientes (
  id              uuid primary key default gen_random_uuid(),
  razon_social    text not null,
  ruc             text unique,
  direccion       text,
  sector          text,
  ciudad_id       int references ciudades,
  industria_id    int references industrias,
  latitud         double precision,
  longitud        double precision,
  responsable_id  uuid references perfiles,      -- "Assigned To"
  recurrente      boolean not null default false,
  activo          boolean not null default true,
  creado_en       timestamptz not null default now()
);

create table contactos_cliente (
  id         uuid primary key default gen_random_uuid(),
  cliente_id uuid not null references clientes on delete cascade,
  nombre     text not null,
  telefono   text,
  correo     text,
  principal  boolean not null default false
);

create table equipos (
  id                 uuid primary key default gen_random_uuid(),
  cliente_id         uuid not null references clientes,
  nombre             text not null,              -- p. ej. "OMI Secador refrigerativo"
  descripcion        text,
  linea_producto_id  int references lineas_producto,
  marca              text,
  modelo             text,
  serie              text,
  anio_fabricacion   int,
  cantidad           int not null default 1,
  foto_url           text,
  foto_placa_url     text,
  activo             boolean not null default true,
  codigo_qr          text unique default encode(gen_random_bytes(6), 'hex'),
  creado_en          timestamptz not null default now()
);

-- ---------- Trabajos (ex hoja "Mantenimiento") ----------
create table trabajos (
  id                    uuid primary key default gen_random_uuid(),
  numero                bigint generated by default as identity unique,  -- "Proyecto Nº"
  equipo_id             uuid not null references equipos,
  titulo                text not null,           -- "Instalación de secador OMI"
  tipo                  tipo_trabajo not null,
  lugar                 lugar_trabajo not null default 'en_cliente',
  estado                estado_trabajo not null default 'abierto',
  asignado_id           uuid references perfiles,
  estado_general_equipo text,
  porcentaje_avance     int check (porcentaje_avance between 0 and 100),
  fecha_ingreso         timestamptz not null default now(),
  fecha_cierre          timestamptz,
  numero_factura        text,
  creado_por            uuid references perfiles,
  creado_en             timestamptz not null default now(),
  constraint cierre_coherente check (
    (estado = 'cerrado') = (fecha_cierre is not null)
  )
);

-- ---------- Visitas (ex hoja "Tasks" + "Check INOut") ----------
create table visitas (
  id                uuid primary key default gen_random_uuid(),
  trabajo_id        uuid not null references trabajos on delete cascade,
  tecnico_id        uuid not null references perfiles,
  descripcion       text not null,
  lugar             lugar_trabajo not null default 'en_cliente',
  programada_inicio timestamptz,
  programada_fin    timestamptz,
  estado            estado_visita not null default 'programada',
  checkin_en        timestamptz,
  checkin_lat       double precision,
  checkin_lng       double precision,
  checkout_en       timestamptz,
  checkout_lat      double precision,
  checkout_lng      double precision,
  horas_trabajadas  numeric(6,2) generated always as (
    case when checkout_en is not null and checkin_en is not null
      then round(extract(epoch from (checkout_en - checkin_en)) / 3600.0, 2) end
  ) stored,
  auto_empresa      boolean not null default false,
  comentarios       text,
  creado_en         timestamptz not null default now(),
  constraint checkout_despues_de_checkin check (checkout_en is null or checkout_en > checkin_en)
);

create table visita_acompanantes (
  visita_id uuid references visitas on delete cascade,
  perfil_id uuid references perfiles,
  primary key (visita_id, perfil_id)
);

create table visita_fotos (
  id        uuid primary key default gen_random_uuid(),
  visita_id uuid not null references visitas on delete cascade,
  url       text not null,
  momento   text check (momento in ('antes', 'durante', 'despues')),
  creado_en timestamptz not null default now()
);

-- Pendientes estructurados (p. ej. "Falta punto de 220 V del secador")
create table pendientes (
  id          uuid primary key default gen_random_uuid(),
  trabajo_id  uuid not null references trabajos on delete cascade,
  visita_id   uuid references visitas,
  descripcion text not null,
  responsable text check (responsable in ('cliente', 'surmaq')),
  resuelto_en timestamptz,
  creado_en   timestamptz not null default now()
);

-- ---------- Mantenimiento programado ----------
create table mantenimientos_programados (
  id            uuid primary key default gen_random_uuid(),
  equipo_id     uuid not null references equipos on delete cascade,
  fecha         date not null,
  comentario    text,
  trabajo_id    uuid references trabajos,       -- trabajo que lo atendió
  creado_en     timestamptz not null default now()
);

-- ---------- Permisos (ex "Leave Tracker") ----------
create table permisos (
  id               uuid primary key default gen_random_uuid(),
  perfil_id        uuid not null references perfiles,
  razon            text not null check (razon in ('permiso', 'permiso_medico', 'vacaciones', 'otro')),
  desde            timestamptz not null,
  hasta            timestamptz not null,
  detalle          text,
  certificado_url  text,
  aprobado         boolean,
  aprobado_por     uuid references perfiles,
  creado_en        timestamptz not null default now(),
  check (hasta > desde)
);

create index on equipos (cliente_id);
create index on trabajos (equipo_id);
create index on trabajos (asignado_id, estado);
create index on visitas (tecnico_id, programada_inicio);
create index on visitas (trabajo_id);
