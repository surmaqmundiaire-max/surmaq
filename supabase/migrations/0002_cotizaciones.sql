-- Optimum Service AI — cotizador de servicio técnico (integrado del cotizador Maquinmotors)
-- Basado en supabase/referencia/cotizador_maquinmotors_original.sql, adaptado al modelo de la app.

-- Nivel y certificaciones del técnico (para armar cuadrillas)
alter table perfiles add column if not exists nivel text check (nivel in ('T1','T2','T3','T4','T5'));
alter table perfiles add column if not exists cert_altura boolean not null default false;
alter table perfiles add column if not exists cert_electrica boolean not null default false;
alter table perfiles add column if not exists cert_pintura boolean not null default false;

-- Configuración editable del cotizador: costos, parámetros, cuadrillas, factores, catálogo, ciudades
create table if not exists config_cotizador (
  clave           text primary key, -- 'costos' | 'params' | 'cuadrillas' | 'tamanos' | 'horarios' | 'alturas' | 'entornos' | 'catalogo' | 'ciudades'
  datos           jsonb not null,
  actualizado     timestamptz not null default now(),
  actualizado_por uuid references perfiles on delete set null
);

create type estado_cotizacion as enum ('Borrador', 'Enviada', 'Aprobada', 'Rechazada', 'Ejecutada');

create table if not exists cotizaciones (
  id            uuid primary key default gen_random_uuid(),
  numero        bigint generated by default as identity unique, -- se muestra como COT-0001
  estado        estado_cotizacion not null default 'Borrador',
  cliente_id    uuid references clientes on delete set null,
  equipo_id     uuid references equipos on delete set null,
  solicitud_id  uuid,
  cliente       text not null,          -- nombre (puede no estar registrado aún)
  ciudad        text not null,
  base          text not null default 'Guayaquil' check (base in ('Guayaquil', 'Quito')),
  total         numeric(12,2) not null default 0,
  horas         numeric(8,2) not null default 0,
  asignados     uuid[] not null default '{}', -- técnicos de la cuadrilla
  datos         jsonb not null,          -- líneas, factores, notas, asignación por puesto
  trabajo_id    uuid references trabajos on delete set null, -- mantenimiento creado al programar
  creado_por    uuid references perfiles on delete set null,
  creado_en     timestamptz not null default now(),
  actualizado   timestamptz not null default now()
);
create index if not exists cotizaciones_estado_idx on cotizaciones (estado);
create index if not exists cotizaciones_cliente_idx on cotizaciones (cliente_id);
create index if not exists cotizaciones_asignados_idx on cotizaciones using gin (asignados);

